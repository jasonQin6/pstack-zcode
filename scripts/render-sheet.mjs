#!/usr/bin/env node
// Render ~/.zcode/pstack-models.md from references/model-map.json.
//
// pstack skills name roles and tiers, never models. On Claude Code the sheet at
// ~/.claude/pstack-models.md holds one resolved model per role. ZCode has no
// model names in common, so this script is the only place a ZCode ID is written:
// edit model-map.json, then regenerate the sheet.
//
// Usage:
//   node scripts/render-sheet.mjs            write the sheet
//   node scripts/render-sheet.mjs --dry-run  print it
//   node scripts/render-sheet.mjs --check    exit 1 when the sheet is stale
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MAP = join(ROOT, "skills/pstack-zcode/references/model-map.json");
const SHEET = join(process.env.ZCODE_CONFIG_DIR ?? join(homedir(), ".zcode"), "pstack-models.md");

const map = JSON.parse(readFileSync(MAP, "utf8"));

function resolveRole(role) {
  const tierName = map.roles[role];
  if (!tierName) return null;
  const tier = map.tiers[tierName];
  if (!tier) throw new Error(`role "${role}" names unknown tier "${tierName}"`);
  const known = (alias) => {
    if (!map.aliases[alias]) throw new Error(`alias "${alias}" is not defined in model-map.json`);
    return alias;
  };
  if (tier.models) return `${role}: ${tier.models.map(known).join(", ")}`;
  const level = tier.thoughtLevel ? ` @${tier.thoughtLevel}` : "";
  return `${role}: ${known(tier.model)}${level}`;
}

const lines = [
  "# pstack model configuration (ZCode)",
  "",
  "# Generated by pstack-zcode: node scripts/render-sheet.mjs",
  "# Source of truth: skills/pstack-zcode/references/model-map.json",
  "# Do not hand-edit. Change the map, then regenerate.",
  "",
  "# Entries are aliases, because pstack's own sheet parser accepts only",
  "# [a-z0-9][a-z0-9.-]* and a ZCode ID holds a colon and a slash. Resolve one",
  "# with: node scripts/resolve-model.mjs <alias>",
  "",
];

// The alias table, so a reader of this sheet can turn an alias into a real ID.
lines.push("# Aliases:");
for (const [alias, id] of Object.entries(map.aliases)) lines.push(`#   ${alias} = ${id}`);
lines.push("");

// Group roles by tier so the file reads as a cost ladder, cheapest first.
const order = ["worker", "default", "strongest", "panel"];
for (const tierName of order) {
  const roles = Object.entries(map.roles)
    .filter(([, t]) => t === tierName)
    .map(([role]) => role);
  if (roles.length === 0) continue;
  for (const role of roles) lines.push(resolveRole(role));
}

lines.push("", `default effort: ${map.effort.default}`, "session hook: on", "");
const text = lines.join("\n");

const dryRun = process.argv.includes("--dry-run");
const check = process.argv.includes("--check");

if (dryRun) {
  process.stdout.write(text);
  process.exit(0);
}

if (check) {
  const current = existsSync(SHEET) ? readFileSync(SHEET, "utf8") : "";
  if (current !== text) {
    console.error(`${SHEET} is out of date. Run: node scripts/render-sheet.mjs`);
    process.exit(1);
  }
  console.log(`${SHEET} is current`);
  process.exit(0);
}

mkdirSync(dirname(SHEET), { recursive: true });
writeFileSync(SHEET, text);
console.log(`wrote ${SHEET}`);
